#!/bin/bash
# Writes the header defining NATIVESCRIPT_VERSION from package.json. Run by the
# "Generate Version header" build phase of the NativeScript target, so a fresh
# clone builds from Xcode without any setup step.
set -euo pipefail

usage() {
  echo "Usage: tools/generate-version-header.sh --package <package.json> --out <header>"
  echo ""
  echo "  --package <path>  package.json to read the version from"
  echo "  --out <path>      header to write (left untouched when already up to date)"
  echo "  -h, --help        show this help"
}

PACKAGE=""
OUT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --package)
      [ $# -ge 2 ] || { echo "--package needs a value" >&2; usage >&2; exit 1; }
      PACKAGE="$2"
      shift 2
      ;;
    --out)
      [ $# -ge 2 ] || { echo "--out needs a value" >&2; usage >&2; exit 1; }
      OUT="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

if [ -z "$PACKAGE" ] || [ -z "$OUT" ]; then
  echo "--package and --out are required" >&2
  usage >&2
  exit 1
fi

VERSION=$(/usr/bin/plutil -extract version raw -o - "$PACKAGE")
if ! [[ "$VERSION" =~ ^[0-9A-Za-z.+-]+$ ]]; then
  echo "error: unexpected version '$VERSION' in $PACKAGE" >&2
  exit 1
fi

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
cat > "$TMP" <<EOF
// Generated by tools/generate-version-header.sh from package.json. Do not edit.
#pragma once
#define NATIVESCRIPT_VERSION "$VERSION"
EOF

# Rewriting an unchanged header would recompile its includers for nothing.
if ! cmp -s "$TMP" "$OUT"; then
  mkdir -p "$(dirname "$OUT")"
  mv "$TMP" "$OUT"
fi
