#include "ProbeEmitter.h"

#include <llvm/ADT/SmallVector.h>
#include <llvm/ADT/StringRef.h>

#include <set>

#include "SwiftSource.h"

namespace Swift {

namespace {

// Every line written between begin() and end() maps to that symbol: the
// compiler reports some errors on the declaration line (parameter types),
// others on the statement.
class Writer {
 public:
  void begin(const std::string& symbolId) { _symbolId = symbolId; }
  void end() { _symbolId.clear(); }

  void line(const std::string& text) {
    _source += text + "\n";
    _line++;
    if (!_symbolId.empty()) {
      _map[_line] = _symbolId;
    }
  }

  ProbeSource finish() {
    return ProbeSource{std::move(_source), std::move(_map)};
  }

 private:
  std::string _source;
  std::map<int, std::string> _map;
  std::string _symbolId;
  int _line = 0;
};

}  // namespace

ProbeSource emitProbes(const Module& module,
                       const Classification& classification) {
  Writer out;
  out.line(
      "// Generated by objc-metadata-generator. Compiler-validation probes "
      "for");
  out.line("// the Swift-generated surface of module " + module.name + ".");
  out.line("import Foundation");
  llvm::SmallVector<llvm::StringRef, 8> imports;
  std::string text = swiftImports(module, classification);
  llvm::StringRef(text).split(imports, '\n', -1, false);
  for (llvm::StringRef line : imports) {
    out.line(line.str());
  }
  out.line("");

  int index = 0;
  for (const auto& entry : module.symbols) {
    const Symbol& symbol = entry.second;
    const Capability* capability = classification.find(entry.first);
    if (!capability || capability->tier != Tier::SwiftGenerated) {
      continue;
    }

    if (isNominalType(symbol.kind)) {
      // Bridged types are copied in and out of boxes and handles, which
      // requires Copyable (not visible in symbol graphs).
      std::string type = qualifiedTypeName(module, symbol);
      std::string availability = availabilityCondition(module, symbol);
      out.begin(symbol.preciseId);
      out.line("// " + symbol.preciseId);
      if (!availability.empty()) {
        out.line("@available(" + availability + ")");
      }
      out.line("func __nsProbe" + std::to_string(index++) +
               "(_ value: " + type + ") -> " + type + " { value }");
      out.end();
      out.line("");
      continue;
    }
    if (!isCallableKind(symbol.kind)) {
      continue;
    }

    Invocation invocation = describeInvocation(module, symbol, *capability);
    std::vector<std::string> parameters;
    if (invocation.needsReceiver) {
      parameters.push_back(
          "_ receiver: " +
          std::string(invocation.receiverIsInout ? "inout " : "") +
          invocation.owner);
    }
    std::vector<std::string> arguments;
    for (size_t i = 0; i < invocation.parameterTypes.size(); i++) {
      std::string name = "a" + std::to_string(i);
      parameters.push_back("_ " + name + ": " + invocation.parameterTypes[i]);
      arguments.push_back(name);
    }
    if (invocation.isSettable) {
      parameters.push_back("_ newValue: " + invocation.resultType);
    }
    std::string signature;
    for (size_t i = 0; i < parameters.size(); i++) {
      signature += (i > 0 ? ", " : "") + parameters[i];
    }

    out.begin(symbol.preciseId);
    out.line("// " + symbol.preciseId);
    // The receiver and parameter types may themselves be gated, so the whole
    // probe carries the availability rather than an #available check.
    if (!invocation.availability.empty()) {
      out.line("@available(" + invocation.availability + ")");
    }
    if (invocation.isMainActor) {
      out.line("@MainActor");
    }
    out.line("func __nsProbe" + std::to_string(index++) + "(" + signature +
             ")" + (invocation.isAsync ? " async" : "") +
             (invocation.isThrowing ? " throws" : "") + " {");
    const std::string receiver = "receiver";
    out.line("  let _: " + invocation.resultType + " = " +
             invocationExpression(invocation, receiver, arguments));
    if (invocation.isSettable) {
      out.line("  " + assignmentStatement(invocation, receiver, "newValue"));
    }
    out.line("}");
    out.end();
    out.line("");
  }
  return out.finish();
}

}  // namespace Swift
